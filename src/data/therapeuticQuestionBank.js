export function getRoleSpecificQuestions(positionId) {
  const entry = roleSpecificQuestionBank[positionId]
  if (!entry) return null
  return {
    label: entry.label,
    questions: entry.questions.map((item) => ({ ...item, followUps: [...item.followUps] })),
  }
}
