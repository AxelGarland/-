/**
 * בנק שאלות לראיון — נשות טיפול (גן / אלוטף).
 * מחליף את questionBank.js הרגיל עבור תפקידי הטיפול המקצועיים.
 */

function q(text, tier = 'standard') {
  return { question: text, followUps: [], tier }
}

