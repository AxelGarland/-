export function isTherapeuticRole(positionId) {
  return THERAPEUTIC_ANCHOR_ROLE_IDS.includes(positionId)
}

export function hasRoleSpecificSectorQuestions(positionId) {
  return THERAPEUTIC_SECTOR_ROLE_IDS.includes(positionId)
}

